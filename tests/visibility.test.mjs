import assert from "node:assert/strict";
import { after, describe, test } from "node:test";
import { runAudit } from "../src/audit.mjs";
import { runCheck } from "../src/check.mjs";
import { auditDelta } from "../src/compare.mjs";
import { ConfigError, loadConfig } from "../src/config.mjs";
import { auditMarkdown, prCommentMarkdown } from "../src/report.mjs";
import { justifiedLines } from "../src/scan.mjs";
import { cli, makeProject } from "./helpers.mjs";

const cleanups = [];
after(() => cleanups.forEach((c) => c()));
const project = (files) => {
  const p = makeProject(files);
  cleanups.push(p.cleanup);
  return p.dir;
};

const APP = {
  "package.json": { name: "x" },
  "src/index.ts": 'import { a } from "./a";\nexport const app = a;\n',
  "src/a.ts": "export const a = (x: any) => x; // justified: JSON boundary, validated by the caller\n",
  "src/gen/client.ts": "// Code generated by openapi-gen. DO NOT EDIT.\nexport const c = 1; // TODO\n",
  "legacy/old.ts": "export const old = 1; // TODO\n",
  "src/a.test.ts": 'import { expect, test } from "vitest";\nimport { a } from "./a";\ntest("a", () => {\n  expect(a(1)).toBe(1);\n});\n',
  "realitygate.config.json": {
    exclude: [{ glob: "legacy/**", reason: "old app, deleted in Q3" }, "vendor-copy/**"],
    disable: [{ id: "R-009", reason: "this is a CLI; console.log is its output" }, "R-010"],
  },
};

describe("exclusions are shown with their reasons", () => {
  test("config keeps exclude and disable reasons; disable still accepts plain ids", () => {
    const cfg = loadConfig(project(APP));
    assert.deepEqual(cfg.exclude, ["legacy/**", "vendor-copy/**"]);
    assert.deepEqual(cfg.disable, ["R-009", "R-010"]);
    assert.deepEqual(cfg.excludeReasons, { "legacy/**": "old app, deleted in Q3" });
    assert.deepEqual(cfg.disableReasons, { "R-009": "this is a CLI; console.log is its output" });
    assert.throws(() => loadConfig(project({ "realitygate.config.json": { disable: [{ reason: "x" }] } })), ConfigError);
  });

  test("R-018's skips are counted per file: entry files and files named by config", () => {
    const dir = project({
      "package.json": { name: "x", main: "src/lib/entry.js" },
      "src/index.ts": "export const app = 1;\n",
      "app/page.tsx": "export default function Page() {\n  return null;\n}\n",
      "src/lib/entry.js": "export const run = 1;\n",
      "src/lib/util.ts": "export const u = 1;\n",
    });
    const byWhat = Object.fromEntries(runCheck(dir).excluded.map((e) => [e.what, e.files]));
    assert.equal(byWhat["R-018 skips entry files"], 2);
    assert.equal(byWhat["R-018 skips files named by config"], 1);
    assert.ok("R-018 skips convention exports" in byWhat);
    const noManifest = runCheck(project({ "src/a.ts": 'import x from "left-pad";\nexport const a = x;\n', "svc/b.py": "import requests\n" }));
    const off = Object.fromEntries(noManifest.excluded.filter((e) => e.what.startsWith("R-014")).map((e) => [e.what, [e.files, e.reason]]));
    assert.deepEqual(off, { "R-014 off for JS/TS": [1, "no package.json to check imports against"], "R-014 off for Python": [1, "no requirements*.txt, pyproject.toml, Pipfile or setup.py to check imports against"] });
    assert.ok(!byWhat["R-014 off for JS/TS"], "a project with package.json has R-014 on");
    const wildcard = runCheck(project({ "package.json": { name: "x", exports: { "./*": "./src/*.js" } }, "src/a.js": "export const a = 1;\n" }));
    assert.deepEqual(wildcard.excluded.filter((e) => e.what.startsWith("R-018")).map((e) => [e.what, e.files]), [["R-018 off", 1]]);
  });

  test("check lists every exclusion, its reason and file count, including a glob that matches nothing", () => {
    const r = runCheck(project(APP));
    const byWhat = Object.fromEntries(r.excluded.map((e) => [e.what, e]));
    assert.deepEqual([byWhat["legacy/**"].files, byWhat["legacy/**"].reason], [1, "old app, deleted in Q3"]);
    assert.deepEqual([byWhat["vendor-copy/**"].files, byWhat["vendor-copy/**"].reason], [0, "no reason given"]);
    assert.equal(byWhat['files headed "Code generated … DO NOT EDIT"'].files, 1);
    assert.equal(byWhat["test files"].files, 1);
    assert.equal(byWhat["rule R-009 disabled"].reason, "this is a CLI; console.log is its output");
    assert.equal(byWhat["rule R-010 disabled"].reason, "no reason given");

    const printed = cli(["check", project(APP)]).stdout;
    assert.match(printed, /excluded +1 +legacy\/\*\* \(old app, deleted in Q3\)/);
    assert.match(printed, /excluded +0 +vendor-copy\/\*\* \(no reason given\)/);
    assert.match(printed, /rule R-009 disabled \(this is a CLI; console\.log is its output\)/);
    assert.match(printed, /justified: 1 line\(s\)/);
  });

  test("the audit carries the same list in JSON and Markdown", () => {
    const r = runAudit(project(APP));
    assert.ok(r.excluded.some((e) => e.what === "legacy/**" && e.reason === "old app, deleted in Q3"));
    const md = auditMarkdown(r);
    assert.match(md, /## Not scanned/);
    assert.match(md, /\| legacy\/\*\* \| 1 \| old app, deleted in Q3 \|/);
  });
});

describe("justified lines are counted and listed", () => {
  test("each justification comment is listed with its reason, in JS, Python and test files", () => {
    const dir = project({
      "src/a.ts": "export const a = (x: any) => x; // justified: JSON boundary\n/* justified: legacy API */ export const b = 1;\n",
      "src/b.py": "X = 1  # it's justified: needed by the old importer\n",
      "src/a.test.ts": 'test.skip("x", () => { // justified: upstream bug #12\n});\n',
    });
    assert.deepEqual(justifiedLines(dir, ["src/a.ts", "src/b.py", "src/a.test.ts"]), [
      { file: "src/a.ts", line: 1, reason: "JSON boundary" },
      { file: "src/a.ts", line: 2, reason: "legacy API" },
      { file: "src/b.py", line: 1, reason: "needed by the old importer" },
      { file: "src/a.test.ts", line: 1, reason: "upstream bug #12" },
    ]);
  });

  test("the marker inside a string or with no comment is not a justification", () => {
    const dir = project({
      "src/a.ts": 'export const help = "add // justified: <reason>";\nexport const re = /justified:/;\nexport const url = "http://x"; // justified: real comment after a string\n',
    });
    assert.deepEqual(justifiedLines(dir, ["src/a.ts"]).map((j) => j.line), [3]);
  });

  test("the audit lists them; the PR comment shows the count and the change against the base", () => {
    const head = runAudit(project(APP));
    assert.deepEqual(head.justified, [{ file: "src/a.ts", line: 1, reason: "JSON boundary, validated by the caller" }]);
    assert.match(auditMarkdown(head), /## Justified \(1\)[\s\S]*`src\/a\.ts:1` \| JSON boundary, validated by the caller/);

    const base = { ...head, justified: [], findings: head.findings };
    const comment = prCommentMarkdown({ ...head, delta: auditDelta(base, head, "main") });
    assert.match(comment, /\*\*1 line\(s\) silenced with `justified:`\*\* \(\+1 vs `main`\)/);
  });
});
