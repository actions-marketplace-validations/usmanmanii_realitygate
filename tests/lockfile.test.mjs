import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { after, describe, test } from "node:test";
import { runAudit } from "../src/audit.mjs";
import { runCheck } from "../src/check.mjs";
import { changedFiles } from "../src/compare.mjs";
import { hasGit, makeProject } from "./helpers.mjs";

const git = (dir, ...args) => execFileSync("git", ["-c", "user.email=t@t.invalid", "-c", "user.name=t", "-c", "commit.gpgsign=false", ...args], { cwd: dir, encoding: "utf8" });

const cleanups = [];
after(() => cleanups.forEach((c) => c()));
const project = (files, opts) => {
  const p = makeProject(files, opts);
  cleanups.push(p.cleanup);
  return p.dir;
};
const r021 = (dir) => runCheck(dir).errors.concat(runCheck(dir).warnings).filter((f) => f.rule === "R-021");
const errors = (dir) => r021(dir).filter((f) => f.severity === "error").map((f) => `${f.file}:${f.line} ${f.text.split(" ")[0]}`);

const PKG = { name: "app", dependencies: { ms: "2.1.3", "@types/ms": "0.7.34", "zodd-imaginary": "1.0.0" } };
// Lockfiles below follow files generated by npm 11, pnpm 11, bun 1.2 and yarn 1 for ms + @types/ms.
const LOCKS = {
  "package-lock.json": JSON.stringify({ lockfileVersion: 3, packages: { "": { name: "app", dependencies: PKG.dependencies }, "node_modules/@types/ms": { version: "0.7.34" }, "node_modules/ms": { version: "2.1.3" } } }),
  "pnpm-lock.yaml": "lockfileVersion: '9.0'\n\nimporters:\n\n  .:\n    dependencies:\n      '@types/ms':\n        specifier: 0.7.34\n        version: 0.7.34\n      ms:\n        specifier: 2.1.3\n        version: 2.1.3\n      zodd-imaginary:\n        specifier: 1.0.0\n        version: 1.0.0\n\npackages:\n\n  '@types/ms@0.7.34':\n    resolution: {integrity: sha512-x}\n\n  ms@2.1.3:\n    resolution: {integrity: sha512-y}\n",
  "yarn.lock": '# yarn lockfile v1\n\n\n"@types/ms@0.7.34":\n  version "0.7.34"\n\nms@2.1.3, ms@^2.1.1:\n  version "2.1.3"\n',
  "bun.lock": '{\n  "lockfileVersion": 1,\n  "workspaces": {\n    "": {\n      "name": "app",\n      "dependencies": {\n        "@types/ms": "0.7.34",\n        "ms": "2.1.3",\n        "zodd-imaginary": "1.0.0",\n      },\n    },\n  },\n  "packages": {\n    "@types/ms": ["@types/ms@0.7.34", "", {}, "sha512-x"],\n\n    "ms": ["ms@2.1.3", "", {}, "sha512-y"],\n  }\n}\n',
};

describe("R-021 declared dependency missing from the lockfile", () => {
  for (const [lock, content] of Object.entries(LOCKS)) {
    test(`${lock}: an invented package that was declared but never installed is an error; locked ones pass`, () => {
      const dir = project({ "package.json": PKG, [lock]: content });
      assert.deepEqual(errors(dir), ["package.json:6 \"zodd-imaginary\""]);
    });
  }

  test("the declared-dependency copies inside pnpm-lock.yaml and bun.lock don't count as locked", () => {
    // Both files above list zodd-imaginary under importers/workspaces; only resolved entries count.
    for (const lock of ["pnpm-lock.yaml", "bun.lock"]) {
      assert.equal(errors(project({ "package.json": PKG, [lock]: LOCKS[lock] })).length, 1, lock);
    }
  });

  test("package-lock v1 and yarn berry are read too", () => {
    const v1 = JSON.stringify({ lockfileVersion: 1, dependencies: { ms: { version: "2.1.3" }, "@types/ms": { version: "0.7.34" } } });
    assert.deepEqual(errors(project({ "package.json": PKG, "package-lock.json": v1 })), ["package.json:6 \"zodd-imaginary\""]);
    const berry = '__metadata:\n  version: 8\n\n"@types/ms@npm:0.7.34":\n  version: 0.7.34\n\n"ms@npm:2.1.3":\n  version: 2.1.3\n';
    assert.deepEqual(errors(project({ "package.json": PKG, "yarn.lock": berry })), ["package.json:6 \"zodd-imaginary\""]);
  });

  test("workspace packages, local paths and a lockfile in a parent folder are handled", () => {
    const dir = project({
      "package.json": { name: "root", private: true, workspaces: ["packages/*"] },
      "packages/ui/package.json": { name: "@acme/ui", dependencies: { ms: "2.1.3" } },
      "packages/web/package.json": { name: "@acme/web", dependencies: { "@acme/ui": "*", local: "file:../local", shared: "workspace:*", ms: "2.1.3" } },
      "yarn.lock": "ms@2.1.3:\n  version \"2.1.3\"\n",
    });
    assert.deepEqual(r021(dir), []);
  });

  test("a lockfile in a parent folder that is not a workspace root belongs to another project", () => {
    const dir = project({
      "package.json": { name: "backend", dependencies: { ms: "2.1.3" } },
      "package-lock.json": LOCKS["package-lock.json"],
      "frontend/package.json": { name: "frontend", dependencies: { vue: "3.5.0" } },
    });
    assert.deepEqual(r021(dir).map((h) => `${h.severity} ${h.file}`), ["warn frontend/package.json"]);
  });

  test("Python: uv.lock, poetry.lock and Pipfile.lock, with name normalisation; build-system requires are skipped", () => {
    const pyproject = '[project]\nname = "svc"\ndependencies = ["Typing_Extensions>=4", "fastjsonx-imaginary"]\n\n[build-system]\nrequires = ["hatchling"]\n';
    const uv = 'version = 1\n\n[[package]]\nname = "svc"\nversion = "0.1.0"\n\n[[package]]\nname = "typing-extensions"\nversion = "4.12.2"\n';
    assert.deepEqual(errors(project({ "pyproject.toml": pyproject, "uv.lock": uv })), ['pyproject.toml:3 "fastjsonx-imaginary"']);
    assert.deepEqual(errors(project({ "pyproject.toml": pyproject, "poetry.lock": uv })), ['pyproject.toml:3 "fastjsonx-imaginary"']);
    const pipfileLock = JSON.stringify({ _meta: { hash: {} }, default: { flask: { version: "==3.1.0" } }, develop: { pytest: { version: "==8.3.0" } } });
    const dir = project({ "requirements.txt": "Flask==3.1.0\npytest\nreqs-imaginary==1.0\n", "Pipfile.lock": pipfileLock });
    assert.deepEqual(errors(dir), ['requirements.txt:3 "reqs-imaginary"']);
  });

  test("Go: every require needs a go.sum line, except modules replaced by a local directory", () => {
    const gomod = "module example.com/svc\n\ngo 1.22\n\nrequire (\n\tgithub.com/google/uuid v1.6.0\n\tgithub.com/imaginary-org/notreal v0.1.0\n\texample.com/internal/lib v0.0.0\n)\n\nreplace example.com/internal/lib => ../lib\n";
    const sum = "github.com/google/uuid v1.6.0 h1:abc=\ngithub.com/google/uuid v1.6.0/go.mod h1:def=\n";
    assert.deepEqual(errors(project({ "go.mod": gomod, "go.sum": sum })), ['go.mod:7 "github.com/imaginary-org/notreal"']);
  });

  test("no lockfile is a warning that says it can't verify, never a silent pass", () => {
    const hits = r021(project({ "package.json": PKG }));
    assert.deepEqual(hits.map((h) => [h.severity, h.text]), [["warn", "can't verify 3 dependencies: no npm lockfile found"]]);
    assert.match(r021(project({ "package.json": PKG, "bun.lockb": "binary" }))[0].text, /bun\.lockb is binary/);
    assert.match(r021(project({ "go.mod": "module x\n\nrequire github.com/google/uuid v1.6.0\n" }))[0].text, /no go\.sum next to go\.mod/);
    assert.deepEqual(r021(project({ "package.json": { name: "x" } })), [], "nothing declared, nothing to verify");
  });

  test("check fails on a missing entry, and the audit charges it to Hallucinated imports but not the can't-verify warning", () => {
    assert.equal(runCheck(project({ "package.json": PKG, "package-lock.json": LOCKS["package-lock.json"], "src/a.ts": 'import ms from "ms";\nexport const a = ms;\n' })).ok, false);
    const src = { "src/a.ts": 'import ms from "ms";\nexport const a = ms;\n' };
    const missing = runAudit(project({ "package.json": PKG, "package-lock.json": LOCKS["package-lock.json"], ...src }));
    const unverified = runAudit(project({ "package.json": PKG, ...src }));
    const cost = (r) => r.categories.find((c) => c.id === "hallucination").items.filter((i) => i.finding?.rule === "R-021").reduce((s, i) => s + i.cost, 0);
    assert.deepEqual([cost(missing), cost(unverified)], [5, 0]);
  });
});

describe("R-021 in change mode", { skip: !hasGit() }, () => {
  test("a changed lockfile rechecks the unchanged manifests", () => {
    const dir = project({ "package.json": { name: "app", dependencies: { ms: "2.1.3" } }, "package-lock.json": LOCKS["package-lock.json"], "src/a.ts": "export const a = 1;\n" }, { git: true });
    git(dir, "add", ".");
    git(dir, "commit", "-q", "-m", "base");
    writeFileSync(join(dir, "package-lock.json"), JSON.stringify({ lockfileVersion: 3, packages: { "": { name: "app" } } }));
    const r = runCheck(dir, { onlyFiles: changedFiles(dir) });
    assert.deepEqual(r.errors.map((e) => `${e.rule} ${e.file}`), ["R-021 package.json"]);
  });
});
